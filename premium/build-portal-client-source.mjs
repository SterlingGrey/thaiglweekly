// Writes the browser client's source as a plain string for the page to embed.
//
// The member page used to embed `portalClient.toString()`. Under a bundler that
// text is the bundler's rewrite of the function, not its source: esbuild with
// keepNames wraps inner functions in a `__name` helper the browser never gets.
// A string constant survives bundling untouched, so the page embeds this file's
// output instead. Run after any change to portal-client.mjs:
//   node premium/build-portal-client-source.mjs
// portal-client.test.mjs fails if the two drift apart.
import { writeFile } from 'node:fs/promises';
import { portalClient } from './portal-client.mjs';

const source = portalClient.toString();
if (/\b__name\s*\(/.test(source)) throw new Error('Run this unbundled: the source already carries a bundler helper');
await writeFile(new URL('./portal-client.source.mjs', import.meta.url),
  `// GENERATED by premium/build-portal-client-source.mjs from portal-client.mjs. Do not edit.\nexport const portalClientSource = ${JSON.stringify(source)};\n`);
console.log(`Wrote portal-client.source.mjs (${source.length} characters).`);
